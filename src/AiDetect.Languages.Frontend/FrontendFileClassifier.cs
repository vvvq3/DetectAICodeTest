using System.Text.RegularExpressions;
using AiDetect.Core.Preprocessing;

namespace AiDetect.Languages.Frontend;

/// <summary>Классификация фронтенд-файлов: исходный код, сгенерированное/вендорное, тесты, архитектурный слой.</summary>
public static partial class FrontendFileClassifier
{
    private static readonly string[] ScriptExtensions = [".ts", ".tsx", ".js", ".jsx", ".mjs", ".cjs", ".mts", ".cts", ".vue"];
    private static readonly string[] StyleExtensions = [".css", ".scss", ".sass", ".less"];

    [GeneratedRegex(@"(^|/)(node_modules|dist|build|out|\.next|\.nuxt|\.output|\.angular|coverage|vendor|vendors|third[_-]party|bower_components|__generated__|generated|gen|\.storybook-static|storybook-static|wwwroot/lib|public/lib|public/vendor|static/vendor|static/lib|assets/vendor|assets/lib|lib/vendor|externals?)/")]
    private static partial Regex GeneratedDir();

    [GeneratedRegex(@"(\.min\.(js|css)|\.bundle\.js|\.chunk\.js|\.d\.ts|\.generated\.\w+|\.gen\.tsx?|\.g\.ts|\.map|-lock\.json|\.lock|\.snap|(^|/)(react-app-env\.d\.ts|vite-env\.d\.ts|serviceWorker\.[jt]s|service-worker\.[jt]s|registerServiceWorker\.[jt]s|reportWebVitals\.[jt]s|setupTests\.[jt]s|polyfills\.ts|routeTree\.gen\.ts|graphql\.tsx?|schema\.graphql\.ts))$")]
    private static partial Regex GeneratedFile();

    [GeneratedRegex(@"@generated|<auto-generated|auto-generated|autogenerated|This file (was|is) (automatically )?generated|Do not edit (this file|the class manually)|DO NOT EDIT|Generated by|generated by (openapi|swagger|graphql-codegen|orval|protoc)", RegexOptions.IgnoreCase)]
    private static partial Regex GeneratedHeader();

    [GeneratedRegex(@"(^|/)(__tests__|__mocks__|tests?|specs?|e2e|cypress|playwright|test-utils|testing)/|\.(spec|test|e2e|cy|stories\.test)\.(t|j)sx?$|(^|/)(setupTests|test-utils|testUtils|jest\.setup|vitest\.setup)\.[jt]sx?$")]
    private static partial Regex TestPath();

    public static bool IsScript(string path) => ScriptExtensions.Any(e => path.EndsWith(e, StringComparison.OrdinalIgnoreCase));

    public static bool IsStyle(string path) => StyleExtensions.Any(e => path.EndsWith(e, StringComparison.OrdinalIgnoreCase));

    /// <summary>HTML-шаблон компонента (Angular *.component.html или шаблоны в src/), но не статическая страница.</summary>
    public static bool IsTemplate(string path)
    {
        var p = CommonFiles.Normalize(path);
        if (!p.EndsWith(".html", StringComparison.Ordinal))
        {
            return false;
        }

        var file = Path.GetFileName(p);
        if (file is "index.html" or "404.html" or "200.html")
        {
            return false;
        }

        return p.EndsWith(".component.html", StringComparison.Ordinal) || p.Contains("/app/") || p.Contains("/components/") ||
               p.Contains("/src/") && !p.Contains("/public/") && !p.Contains("/static/") && !p.Contains("/wwwroot/");
    }

    public static bool IsSource(string path) => IsScript(path) || IsStyle(path) || IsTemplate(path);

    public static bool IsGenerated(string path, string? content)
    {
        var p = CommonFiles.Normalize(path);
        if (GeneratedDir().IsMatch(p) || GeneratedFile().IsMatch(p))
        {
            return true;
        }

        if (p.Contains("/migrations/") || p.Contains("/locales/") && p.EndsWith(".js", StringComparison.Ordinal) || p.Contains("/i18n/") && Regex.IsMatch(p, @"/[a-z]{2}(-[a-z]{2})?\.(js|ts)$"))
        {
            return true;
        }

        if (content is null)
        {
            return false;
        }

        var head = content.Length > 800 ? content[..800] : content;
        if (GeneratedHeader().IsMatch(head))
        {
            return true;
        }

        // Минифицированный код: очень длинные строки.
        if (content.Length > 3000)
        {
            int newLines = content.Count(ch => ch == '\n') + 1;
            if (content.Length / newLines > 400)
            {
                return true;
            }
        }

        // Скелет Angular CLI: spec только с «should create».
        if (p.EndsWith(".spec.ts", StringComparison.Ordinal) && IsCliSkeletonSpec(content))
        {
            return true;
        }

        return false;
    }

    [GeneratedRegex(@"\bit\(\s*['""`]([^'""`]+)['""`]")]
    private static partial Regex ItTitle();

    public static bool IsCliSkeletonSpec(string content)
    {
        var titles = ItTitle().Matches(content).Select(m => m.Groups[1].Value).ToList();
        return titles.Count is >= 1 and <= 2 && titles.All(t => t is "should create" or "should be created" or "should create the app") &&
               content.Contains("TestBed", StringComparison.Ordinal);
    }

    public static bool IsTestFile(string path, string? content)
    {
        var p = CommonFiles.Normalize(path);
        if (TestPath().IsMatch(p))
        {
            return !p.EndsWith(".stories.tsx", StringComparison.Ordinal) && !p.EndsWith(".stories.ts", StringComparison.Ordinal);
        }

        return false;
    }

    public static Layer ClassifyLayer(string path, string? content)
    {
        var p = CommonFiles.Normalize(path);
        var file = Path.GetFileName(p);
        if (CommonFiles.IsMarkdown(p))
        {
            return Layer.Documentation;
        }

        if (file is "package.json" or "angular.json" or "tsconfig.json" or "nx.json" or "lerna.json" or "workspace.json" || file.StartsWith("tsconfig", StringComparison.Ordinal) ||
            Regex.IsMatch(file, @"^(vite|webpack|rollup|jest|vitest|babel|postcss|tailwind|karma|next|nuxt|vue|svelte|astro|playwright|cypress|eslint|prettier|stylelint)\.config\.") ||
            file.StartsWith(".eslintrc", StringComparison.Ordinal) || file.StartsWith(".prettierrc", StringComparison.Ordinal) || file.StartsWith(".babelrc", StringComparison.Ordinal))
        {
            return Layer.BuildProject;
        }

        if (p.Contains("/i18n/") || p.Contains("/locales/") || p.Contains("/locale/") || p.Contains("/translations/") || p.Contains("/lang/") && p.EndsWith(".json", StringComparison.Ordinal))
        {
            return Layer.I18n;
        }

        if (p.EndsWith(".json", StringComparison.Ordinal) || p.EndsWith(".yml", StringComparison.Ordinal) || p.EndsWith(".yaml", StringComparison.Ordinal) ||
            file.StartsWith("environment", StringComparison.Ordinal))
        {
            return Layer.Configuration;
        }

        if (!IsSource(p))
        {
            return Layer.Other;
        }

        if (IsTestFile(p, content))
        {
            return Layer.Tests;
        }

        if (p.Contains(".stories.", StringComparison.Ordinal) || p.Contains("/stories/"))
        {
            return Layer.Stories;
        }

        if (IsStyle(p))
        {
            return Layer.Styles;
        }

        if (IsTemplate(p))
        {
            return Layer.Template;
        }

        var stem = Path.GetFileNameWithoutExtension(p);
        if (p.Contains("/hooks/") || p.Contains("/composables/") || Regex.IsMatch(Path.GetFileName(path), @"^use[A-Z]\w*\.(t|j)sx?$"))
        {
            return Layer.Hook;
        }

        if (Regex.IsMatch(file, @"\.(store|reducer|reducers|actions|action|effects|selectors|slice|state|mutations|getters)\.(t|j)s$") || p.Contains("/store/") ||
            p.Contains("/stores/") || p.Contains("/redux/") || p.Contains("/reducers/") || p.Contains("/slices/") || p.Contains("/state/") || p.Contains("/vuex/") ||
            p.Contains("/ngrx/") || p.Contains("/pinia/"))
        {
            return Layer.State;
        }

        if (Regex.IsMatch(file, @"(routing\.module|\.routes|-routes|routes|router)\.(t|j)sx?$") || p.Contains("/router/") || p.Contains("/routes/"))
        {
            return Layer.Routing;
        }

        if (Regex.IsMatch(file, @"\.(guard|interceptor|resolver|middleware)\.(t|j)s$") || p.Contains("/guards/") || p.Contains("/interceptors/") || p.Contains("/middleware/"))
        {
            return Layer.Middleware;
        }

        if (file.EndsWith(".module.ts", StringComparison.Ordinal) || file is "app.config.ts" or "main.ts" or "main.js" or "index.tsx" && p.Count(ch => ch == '/') <= 1)
        {
            return Layer.Module;
        }

        if (Regex.IsMatch(file, @"\.(validator|validators|validation|schema)\.(t|j)s$") || p.Contains("/validators/") || p.Contains("/validation/") || p.Contains("/schemas/"))
        {
            return Layer.Validation;
        }

        if (p.Contains("/api/") || Regex.IsMatch(file, @"(api|client|http)\.(t|j)s$"))
        {
            return Layer.ApiClient;
        }

        if (file.EndsWith(".service.ts", StringComparison.Ordinal) || file.EndsWith(".service.js", StringComparison.Ordinal) || p.Contains("/services/"))
        {
            return Layer.Service;
        }

        if (Regex.IsMatch(file, @"(\.types?|\.model|\.models|\.interface|\.interfaces|\.dto|\.enum|\.enums)\.(t|j)s$") || stem is "types" or "models" or "interfaces" ||
            p.Contains("/types/") || p.Contains("/models/") || p.Contains("/interfaces/") || p.Contains("/typings/"))
        {
            return Layer.Types;
        }

        if (Regex.IsMatch(file, @"\.(utils?|helpers?)\.(t|j)s$") || stem is "utils" or "helpers" or "util" or "helper" || p.Contains("/utils/") ||
            p.Contains("/helpers/") || p.Contains("/lib/") || p.Contains("/shared/utils"))
        {
            return Layer.Utils;
        }

        if (Regex.IsMatch(file, @"\.(constants?|config)\.(t|j)s$") || stem is "constants" or "const" or "config" || p.Contains("/constants/"))
        {
            return Layer.Constants;
        }

        if (p.EndsWith(".vue", StringComparison.Ordinal) || Regex.IsMatch(file, @"\.(component|directive|pipe|page|view|container)\.(t|j)sx?$") ||
            p.Contains("/components/") || p.Contains("/pages/") || p.Contains("/views/") || p.Contains("/containers/") || p.Contains("/layouts/") ||
            p.EndsWith(".tsx", StringComparison.Ordinal) || p.EndsWith(".jsx", StringComparison.Ordinal))
        {
            return Layer.Component;
        }

        return Layer.Other;
    }
}
