using System.Text.RegularExpressions;

namespace AiDetect.Core.Preprocessing;

/// <summary>Архитектурный слой, к которому относится файл. Нужен для признака «связный многослойный дифф».</summary>
public enum Layer
{
    Other,
    Controller,
    Service,
    Handler,
    Repository,
    Domain,
    Contracts,
    DependencyInjection,
    Validation,
    Options,
    Mapping,
    Middleware,
    Migration,
    Tests,
    Documentation,
    Configuration,
    BuildProject,
}

public static partial class FileClassifier
{
    private static readonly string[] GeneratedSuffixes =
    [
        ".designer.cs", ".g.cs", ".g.i.cs", ".generated.cs", ".assemblyinfo.cs", "assemblyinfo.cs", "globalusings.g.cs",
    ];

    public static bool IsCSharp(string path) => path.EndsWith(".cs", StringComparison.OrdinalIgnoreCase);

    public static bool IsMarkdown(string path) => path.EndsWith(".md", StringComparison.OrdinalIgnoreCase);

    /// <summary>Сгенерированный или служебный код, который исключается из анализа (по рекомендации исследования).</summary>
    public static bool IsGenerated(string path, string? content)
    {
        var p = Normalize(path);
        if (GeneratedSuffixes.Any(s => p.EndsWith(s, StringComparison.Ordinal)))
        {
            return true;
        }

        if (p.Contains("/obj/") || p.Contains("/bin/") || p.StartsWith("obj/") || p.StartsWith("bin/"))
        {
            return true;
        }

        if (p.Contains("/migrations/") || p.StartsWith("migrations/") || p.EndsWith("modelsnapshot.cs", StringComparison.Ordinal))
        {
            return true;
        }

        if (content is not null)
        {
            var head = content.Length > 600 ? content[..600] : content;
            if (head.Contains("<auto-generated", StringComparison.OrdinalIgnoreCase) ||
                head.Contains("[Migration(", StringComparison.Ordinal) ||
                head.Contains("This code was generated by a tool", StringComparison.OrdinalIgnoreCase))
            {
                return true;
            }
        }

        return false;
    }

    public static bool IsTestFile(string path, string? content)
    {
        var p = Normalize(path);
        if (p.Contains("test") && (p.Contains(".tests/") || p.Contains(".test/") || p.Contains("/tests/") || p.Contains("/test/") ||
                                   p.StartsWith("tests/") || p.StartsWith("test/") || p.EndsWith("tests.cs") || p.EndsWith("test.cs") ||
                                   p.Contains(".unittests") || p.Contains(".integrationtests") || p.Contains("specs/")))
        {
            return true;
        }

        if (content is not null)
        {
            return TestAttribute().IsMatch(content);
        }

        return false;
    }

    [GeneratedRegex(@"\[(Fact|Theory|Test|TestCase|TestMethod|DataTestMethod)\b")]
    private static partial Regex TestAttribute();

    public static Layer ClassifyLayer(string path, string? content)
    {
        var p = Normalize(path);
        var file = System.IO.Path.GetFileName(p);

        if (IsMarkdown(p))
        {
            return Layer.Documentation;
        }

        if (p.EndsWith(".csproj") || p.EndsWith(".props") || p.EndsWith(".targets") || p.EndsWith(".sln") || p.EndsWith(".slnx"))
        {
            return Layer.BuildProject;
        }

        if (file.StartsWith("appsettings") || p.EndsWith(".json") || p.EndsWith(".yml") || p.EndsWith(".yaml") || p.EndsWith(".config"))
        {
            return Layer.Configuration;
        }

        if (!IsCSharp(p))
        {
            return Layer.Other;
        }

        if (IsTestFile(p, content))
        {
            return Layer.Tests;
        }

        if (p.Contains("/migrations/") || p.StartsWith("migrations/"))
        {
            return Layer.Migration;
        }

        if (file.EndsWith("controller.cs") || p.Contains("/controllers/") || file.EndsWith("endpoints.cs") || p.Contains("/endpoints/") ||
            (content?.Contains(": ControllerBase") ?? false) || (content?.Contains(": Controller") ?? false))
        {
            return Layer.Controller;
        }

        if (file is "program.cs" or "startup.cs" or "dependencyinjection.cs" || file.Contains("servicecollection") ||
            file.EndsWith("extensions.cs") && (content?.Contains("IServiceCollection") ?? false) ||
            file.EndsWith("module.cs") && (content?.Contains("IServiceCollection") ?? false))
        {
            return Layer.DependencyInjection;
        }

        if (file.EndsWith("validator.cs") || p.Contains("/validators/") || p.Contains("/validation/"))
        {
            return Layer.Validation;
        }

        if (file.EndsWith("options.cs") || file.EndsWith("settings.cs") || p.Contains("/options/"))
        {
            return Layer.Options;
        }

        if (file.EndsWith("profile.cs") || file.Contains("mapper") || file.Contains("mapping") || p.Contains("/mappings/") || p.Contains("/mapping/"))
        {
            return Layer.Mapping;
        }

        if (file.Contains("middleware") || p.Contains("/middleware") || file.EndsWith("filter.cs") || p.Contains("/filters/"))
        {
            return Layer.Middleware;
        }

        if (file.EndsWith("handler.cs") || file.EndsWith("command.cs") || file.EndsWith("query.cs") || p.Contains("/handlers/") ||
            p.Contains("/commands/") || p.Contains("/queries/") || file.EndsWith("consumer.cs"))
        {
            return Layer.Handler;
        }

        if (file.EndsWith("repository.cs") || p.Contains("/repositories/") || file.EndsWith("dbcontext.cs") || p.Contains("/persistence/") ||
            p.Contains("/data/") || file.EndsWith("configuration.cs") && (content?.Contains("IEntityTypeConfiguration") ?? false) ||
            p.Contains("/infrastructure/"))
        {
            return Layer.Repository;
        }

        if (file.EndsWith("service.cs") || p.Contains("/services/") || file.EndsWith("manager.cs") || file.EndsWith("provider.cs"))
        {
            return Layer.Service;
        }

        if (file.EndsWith("dto.cs") || file.EndsWith("request.cs") || file.EndsWith("response.cs") || p.Contains("/contracts/") ||
            p.Contains("/dtos/") || p.Contains("/dto/") || p.Contains("/viewmodels/") || file.EndsWith("viewmodel.cs") || p.Contains("/models/requests") ||
            p.Contains("/models/responses"))
        {
            return Layer.Contracts;
        }

        if (p.Contains("/entities/") || p.Contains("/domain/") || p.Contains("/models/") || p.Contains("/aggregates/"))
        {
            return Layer.Domain;
        }

        if (file.StartsWith("i") && file.Length > 2 && char.IsUpper(System.IO.Path.GetFileName(path)[1]))
        {
            // Интерфейс без явного слоя — считаем сервисным контрактом.
            return Layer.Service;
        }

        return Layer.Other;
    }

    public static string LayerTitle(Layer layer) => layer switch
    {
        Layer.Controller => "контроллеры/эндпоинты",
        Layer.Service => "сервисы",
        Layer.Handler => "обработчики/команды",
        Layer.Repository => "доступ к данным",
        Layer.Domain => "доменные модели",
        Layer.Contracts => "DTO/контракты",
        Layer.DependencyInjection => "регистрация DI",
        Layer.Validation => "валидация",
        Layer.Options => "настройки/options",
        Layer.Mapping => "маппинг",
        Layer.Middleware => "middleware/фильтры",
        Layer.Migration => "миграции",
        Layer.Tests => "тесты",
        Layer.Documentation => "документация",
        Layer.Configuration => "конфигурация",
        Layer.BuildProject => "проектные файлы",
        _ => "прочее",
    };

    private static string Normalize(string path) => path.Replace('\\', '/').ToLowerInvariant();
}
